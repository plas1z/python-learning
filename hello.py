# Урок 1. ОБРАЗЕЦ: программа-знакомство (разобрали вместе с Claude)

# 1. Спрашиваем имя.
# input() печатает вопрос и ждёт, пока ты введёшь текст и нажмёшь Enter.
# Всё, что человек ввёл, приходит СТРОКОЙ (текстом) — даже если он введёт цифры.
# Эту строку мы кладём в переменную name — «коробку» с ярлыком name.
name = input("Как тебя зовут? ")

# 2. Спрашиваем возраст.
# С возрастом нужно будет СЧИТАТЬ (+10 лет, год рождения), а считать можно только с числами.
# Поэтому input() оборачиваем в int() — оно превращает строку "25" в число 25.
age = int(input("Сколько тебе лет? "))

# 3. Считаем. Результат каждого вычисления кладём в свою переменную.
future_age = age + 10        # сколько будет через 10 лет
birth_year = 2026 - age      # примерный год рождения

# 4. Выводим результат.
# Буква f перед кавычками — «f-строка»: внутри фигурных скобок {} подставляются
# значения переменных. Питон сам превратит число в текст при печати.
print(f"Привет, {name}! Через 10 лет тебе будет {future_age}, а родился ты примерно в {birth_year}.")
