# Урок 3. ОБРАЗЕЦ: циклы — программа повторяет действия
# Часть 1: while — «повторяй, ПОКА условие верно»

# Копилки. Создаются ДО цикла и сразу с нуля:
# нельзя бросить монету в копилку, которой ещё не существует.
total = 0     # сюда накопим сумму покупок
count = 0     # сюда — количество товаров

print("Касса. Вводи цены. Когда закончишь — напиши «конец».")

# Первый ввод — ДО цикла: условию while нужен материал для самой первой проверки.
answer = input("Цена: ")

# while работает как if, который после выполнения тела ВОЗВРАЩАЕТСЯ и проверяет снова.
# Условие True — ещё круг. Стало False — цикл отпускает, программа идёт дальше.
while answer != "конец":
    # Сначала убедились, что это не «конец», и только теперь превращаем в число.
    # Помнишь int("двадцать") из урока 1? float("конец") падает точно так же.
    price = float(answer)

    # Копилка. Правая часть считается по СТАРОМУ значению total,
    # результат кладётся обратно в total. Это НЕ тавтология — см. разбор в чате.
    total = total + price
    count = count + 1

    # ВАЖНЕЙШАЯ строка урока: обновляем answer В КОНЦЕ тела.
    # Без неё answer не меняется, условие вечно True — вечный цикл.
    # Аварийный выход из вечного цикла: Ctrl+C в терминале.
    answer = input("Цена: ")

print(f"Товаров: {count}, к оплате: {total:.2f} ₽")


# Часть 2: for + range — «повтори известное число раз»
# range(5) даёт числа 0,1,2,3,4 — ПЯТЬ штук, НО ДО ПЯТИ, без самой пятёрки.
# Классическая ловушка: последний круг range(5) — четвёрка, не пятёрка!

deposit = float(input("\nСумма вклада: "))
for month in range(1, 13):        # числа 1..12: начали с 1, потому что месяца №0 не бывает
    deposit = deposit * 1.02      # +2% каждый месяц, проценты на проценты
    print(f"Месяц {month}: {deposit:.2f} ₽")

print(f"Итого через год: {deposit:.2f} ₽")
