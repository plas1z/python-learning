# ЭТАП 1. ОБРАЗЕЦ: меню-цикл на двух пунктах-пробниках
# Это скелет, на который ты натянешь все 7 пунктов Кошелька.

print("=== ДЕМО-МЕНЮ ===")
print("1 — поздороваться")
print("0 — выход")

# ответ держим СТРОКОЙ: тогда «7», «двести», «ыыы» — просто не совпадут
# ни с одним пунктом, и программа не упадёт
answer = input("Выбор: ")
while answer != "0":                      # «0» — выход, sentinel из спеки
    if answer == "1":
        print("Привет! Я пункт меню. Скоро тут будет добавление траты")
    else:
        print("Нет такого пункта")

    answer = input("Выбор: ")             # последняя строка тела — всегда

print("Пока!")
