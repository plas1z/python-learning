# Урок 4. ОБРАЗЕЦ: списки — данные помнятся, а не только суммируются
# Список (list) — коробка с ячейками, пронумерованными с НУЛЯ.

cart = []                                  # пустой список — копилка для строк

item = input("Товар (или «стоп»): ")
while item != "стоп":                      # цикл из урока 3, sentinel тот же
    cart.append(item)                      # append = положить в конец списка
    item = input("Товар (или «стоп»): ")   # последняя строка тела — как учили

print(f"В корзине {len(cart)} шт.")        # len() = сколько ячеек
print("Первый:", cart[0], "· последний:", cart[-1])   # [0] — первый, [-1] — последний
print("Первые два:", cart[:2])             # срез: с начала ДО индекса 2 (без него)

for name in cart:                          # for перебирает список сам
    print("—", name)

# Часть 2: строка → список
line = input("Покупки через запятую: ")
for word in line.split(","):               # split режет строку по разделителю
    print("·", word.strip())               # strip срезает пробелы по краям
