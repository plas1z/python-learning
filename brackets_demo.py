# ДЕМО: три вида скобок в живом коде. Запусти и сверяй вывод со строками.

# ── ( ) круглые: «выполни действие» ──────────────────────
print("Привет!")              # вызов команды print — круглые
x = int("25")                 # вызов команды int — круглые
print(x + 5)                  # снова вызов print — круглые

ok = (5 > 3) and (2 > 1)      # группировка в условии — круглые
print("Оба условия верны?", ok)

# ── [ ] квадратные: список и «дай элемент» ───────────────
names = ["молоко", "хлеб", "сыр"]    # создать список — квадратные
print(names)                         # показать весь список
print(names[0])                      # дай элемент № 0
print(names[2])                      # дай элемент № 2
print(names[:2])                     # срез: первые два

# ── { } фигурные: СОЗДАТЬ словарь, [ ] квадратные: ЧИТАТЬ ──
stock = {"кефир": 95.0, "сыр": 550.0}   # создать словарь — фигурные
print(stock["сыр"])                     # читать словарь — КВАДРАТНЫЕ!

# ── { } внутри f-строки: окно в тексте, НЕ код словаря ──
name = "Саша"
print(f"Привет, {name}! Сыр стоит {stock['сыр']:.2f} ₽")

# Итог одной строкой:
print("() — действие, [] — дай элемент, {} — собери словарь")
