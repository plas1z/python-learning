# Урок 7. ОБРАЗЕЦ: файлы (память), try/except (иммунитет), множества

# ФАЙЛЫ: данные живут между запусками программы.
# Режимы: "w" — записать (СТИРАЕТ прежнее!), "a" — дописать в конец, "r" — читать.
# encoding="utf-8" — обязательно, иначе русский текст превратится в кракозябры.

with open("shop_log.txt", "w", encoding="utf-8") as f:   # with сам закроет файл
    f.write("молоко 80\n")          # \n — перевод строки, без него всё слипнется
    f.write("хлеб 55\n")

with open("shop_log.txt", "a", encoding="utf-8") as f:   # "a" = append, дописать
    f.write("сыр 550\n")

with open("shop_log.txt", encoding="utf-8") as f:        # без режима = чтение
    lines = f.readlines()           # весь файл → список строк

for line in lines:
    print("строка:", line.strip())  # strip срезает \n на конце строки

# ИСКЛЮЧЕНИЯ: обещание из урока 1 исполнено — int("двадцать") больше не убивает
answer = "двадцать"
try:
    number = int(answer)            # рискованное место — в try
    print(number * 2)
except ValueError:                  # упало ИМЕННО с ValueError — спасаем
    print("Это не число, пропускаю")

# МНОЖЕСТВА (set): {..} без двоеточий; хранит БЕЗ повторов; порядок забыт
a = {"молоко", "хлеб", "сыр"}
b = {"хлеб", "кефир"}
print(a | b)        # объединение: всё без дублей
print(a & b)        # пересечение: что есть в обоих
print("хлеб" in a)  # in работает и тут
