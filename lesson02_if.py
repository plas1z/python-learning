# Урок 2. ОБРАЗЕЦ: система скидок — программа принимает решения
# Новые conceptы: if / elif / else, сравнения, True/False, and/or, ОТСТУПЫ

# Условие — это вопрос, на который Python отвечает «да» (True) или «нет» (False).
# Сравнения:  >  <  >=  <=  == (равно!)  != (не равно)
# ВНИМАНИЕ: = (одинарное) — это «положить в переменную». == (двойное) — «сравнить».
total = float(input("Сумма покупки: "))

# if/elif/else читаются СВЕРХУ ВНИЗ.
# Python проверяет условия по очереди и выполняет ТОЛЬКО ПЕРВОЕ подошедшее —
# остальные пропускает, даже если они тоже верны. else — «во всех прочих случаях».
# Двоеточие в конце строки условия — обязательно.
# ОТСТУП (4 пробела) показывает, что находится ВНУТРИ ветки. Это не красота,
# а синтаксис: без отступа или с кривым отступом Python упадёт с IndentationError.
if total >= 5000:
    discount = 0.15          # 15%
    print("Вам положена скидка 15% — вы крупный покупатель!")
elif total >= 2000:
    discount = 0.10          # 10%
elif total >= 500:
    discount = 0.05          # 5%
else:
    discount = 0             # без скидки

# Обычная математика урока 1: (1 - discount) = доля цены, которую платит покупатель
final = total * (1 - discount)
# :.2f — два знака после точки (уже знаешь), :.0% — число как проценты, 0.15 -> "15%"
print(f"Итого к оплате: {final:.2f} ₽ (скидка {discount:.0%})")

# Логические связки:
#   or  — «или»: достаточно ОДНОГО верного условия
#   and — «и»: нужны ОБА верных
# Сравнение возвращает значение True/False — его можно сразу сохранить в переменную:
is_vip = input("Вы VIP-клиент? (да/нет): ") == "да"

if is_vip or total >= 3000:
    print("Доставка бесплатная.")
else:
    print("Доставка 300 ₽.")
