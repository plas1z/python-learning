# Урок 5. ОБРАЗЕЦ: словарь — данные под ЯРЛЫКАМИ, а не под номерами
# Список: ячейка по номеру cart[0]. Словарь: ячейка по имени stock["сыр"].

stock = {                 # словарь: {ключ: значение}
    "молоко": 80.0,
    "хлеб": 50.0,
    "сыр": 550.0,
}

print("Склад:", stock)
print("Сыр стоит:", stock["сыр"])      # доступ по КЛЮЧУ — не путать с индексом

if "кефир" in stock:                   # in: «есть ли такой ключ в словаре?»
    print("кефир есть")
else:
    print("кефира нет")

stock["кефир"] = 95.0                  # новый ключ = добавился
stock["хлеб"] = 55.0                   # существующий ключ = ПЕРЕЗАПИСАЛСЯ (переоценка)

print(f"Теперь товаров: {len(stock)}") # len считает ключи

# Паттерн «чемпион»: ищем самое большое, перебирая всех
best = None            # имя действующего чемпиона (пока пустое)
best_price = 0         # его результат (любой кандидат с ценой > 0 его обойдёт)
for name in stock:     # for по словарю идёт по КЛЮЧАМ
    if stock[name] > best_price:   # встретили дороже чемпиона?
        best = name                # новый чемпион —
        best_price = stock[name]   # запоминаем и имя, и результат

print(f"Самый дорогой: {best} за {best_price:.2f} ₽")
